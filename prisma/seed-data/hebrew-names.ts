export function buildFullName(seedIndex: number): { name: string; gender: "male" | "female" } {
  const isFemale = seedIndex % 2 === 0;
  const firstNames = isFemale ? HEBREW_FIRST_NAMES_FEMALE : HEBREW_FIRST_NAMES_MALE;
  const firstName = firstNames[seedIndex % firstNames.length];
  const surname = HEBREW_SURNAMES[Math.floor(seedIndex / 3) % HEBREW_SURNAMES.length];
  return { name: `${firstName} ${surname}`, gender: isFemale ? "female" : "male" };
}
